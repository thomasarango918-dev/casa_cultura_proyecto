-- =============================================================================
--  Casa de la Cultura de San Pedro de los Milagros
--  FASE 2: Radicación pública de solicitudes de inscripción
--  Script de actualización PostgreSQL (14+). Se ejecuta DESPUÉS de casacultura.sql.
-- -----------------------------------------------------------------------------
--  Ejecución (pgAdmin > Query Tool sobre la base casacultura, o por consola):
--      psql -U casacultura -d casacultura -f database/fase2_solicitudes.sql
--
--  Qué hace:
--    1. Reemplaza las tablas de solicitudes del esquema inicial
--       (TBL_SolicitudInscripcion y TBL_ArchivosSolicitud), que nunca se usaron,
--       por la estructura de la Fase 2. SOLO lo hace si están vacías: si tienen
--       datos, el script se detiene sin cambiar nada.
--    2. Crea TBL_DocumentoInscripcion (archivos adjuntos de cada solicitud).
--    3. Crea TBL_ConsecutivoRadicado (contador atómico de RAD-AAAA-XXXX por año).
--    4. Registra los programas ofrecidos (si aún no existen).
--
--  Es idempotente: ejecutarlo de nuevo sobre una base ya actualizada no cambia nada.
--  No modifica TBL_Usuarios, TBL_Roles ni TBL_TipoDocumento.
-- =============================================================================

BEGIN;

SET client_encoding = 'UTF8';


-- 1. Retiro de la estructura anterior (solo si está vacía)
-- =============================================================================
-- La estructura nueva se reconoce por la columna Numero_Radicado. Si no existe,
-- las tablas de solicitudes corresponden al esquema inicial y se reemplazan.
DO $$
DECLARE
    v_filas BIGINT := 0;
    v_total BIGINT := 0;
    v_tabla TEXT;
BEGIN
    IF to_regclass('tbl_solicitudinscripcion') IS NULL
       OR EXISTS (
           SELECT 1 FROM information_schema.columns
           WHERE table_schema = current_schema()
             AND table_name = 'tbl_solicitudinscripcion'
             AND column_name = 'numero_radicado'
       ) THEN
        RETURN;  -- No hay estructura anterior o ya está actualizada.
    END IF;

    FOREACH v_tabla IN ARRAY ARRAY['tbl_documentoinscripcion', 'tbl_archivossolicitud', 'tbl_solicitudinscripcion'] LOOP
        IF to_regclass(v_tabla) IS NOT NULL THEN
            EXECUTE format('SELECT count(*) FROM %I', v_tabla) INTO v_filas;
            v_total := v_total + v_filas;
        END IF;
    END LOOP;

    IF v_total > 0 THEN
        RAISE EXCEPTION
            'Las tablas de solicitudes del esquema anterior contienen % registro(s). '
            'Respáldelos y vacíe las tablas antes de aplicar la Fase 2.', v_total;
    END IF;

    DROP TABLE IF EXISTS tbl_documentoinscripcion;
    DROP TABLE IF EXISTS tbl_archivossolicitud;
    DROP TABLE tbl_solicitudinscripcion;
    RAISE NOTICE 'Estructura anterior de solicitudes retirada (estaba vacía).';
END
$$;


-- 2. TBL_SolicitudInscripcion
-- =============================================================================
CREATE TABLE IF NOT EXISTS TBL_SolicitudInscripcion (
    ID                       INT GENERATED BY DEFAULT AS IDENTITY,
    Numero_Radicado          VARCHAR(50)  NOT NULL,
    Nombres                  VARCHAR(100) NOT NULL,
    Apellidos                VARCHAR(100) NOT NULL,
    Tipo_Documento           VARCHAR(20)  NOT NULL,
    Numero_Documento         VARCHAR(20)  NOT NULL,
    Correo_Electronico       VARCHAR(150) NOT NULL,
    Telefono                 VARCHAR(20)  NULL,
    Programa_ID              INT          NOT NULL,
    Estado                   VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',
    Justificacion_Respuesta  TEXT         NULL,
    Fecha_Radicacion         TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    Fecha_Evaluacion         TIMESTAMP    NULL,
    Evaluado_Por             INT          NULL,
    CONSTRAINT pk_solicitud                PRIMARY KEY (ID),
    CONSTRAINT uq_solicitud_radicado       UNIQUE (Numero_Radicado),
    CONSTRAINT ck_solicitud_estado         CHECK (Estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO')),
    CONSTRAINT ck_solicitud_correo_min     CHECK (Correo_Electronico = LOWER(Correo_Electronico)),
    -- Una solicitud evaluada siempre tiene justificación.
    CONSTRAINT ck_solicitud_justificacion  CHECK (Estado = 'PENDIENTE' OR Justificacion_Respuesta IS NOT NULL),
    CONSTRAINT fk_solicitud_tipo_documento FOREIGN KEY (Tipo_Documento)
        REFERENCES TBL_TipoDocumento (Tipo_Doc) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_programa       FOREIGN KEY (Programa_ID)
        REFERENCES TBL_Programas (ID)        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_evaluador      FOREIGN KEY (Evaluado_Por)
        REFERENCES TBL_Usuarios (ID)         ON UPDATE CASCADE ON DELETE SET NULL
);
COMMENT ON TABLE  TBL_SolicitudInscripcion                         IS 'Solicitudes de inscripción radicadas desde el formulario público.';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Numero_Radicado         IS 'Número de radicado entregado al ciudadano (RAD-AAAA-XXXX).';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Tipo_Documento          IS 'Sigla del tipo de documento (CC, TI, CE...).';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Estado                  IS 'PENDIENTE, APROBADO o RECHAZADO.';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Justificacion_Respuesta IS 'Motivo de la decisión, obligatorio al aprobar o rechazar.';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Evaluado_Por            IS 'Funcionario que evaluó la solicitud (NULL mientras esté pendiente).';

CREATE INDEX IF NOT EXISTS ix_solicitud_estado           ON TBL_SolicitudInscripcion (Estado);
CREATE INDEX IF NOT EXISTS ix_solicitud_programa         ON TBL_SolicitudInscripcion (Programa_ID);
CREATE INDEX IF NOT EXISTS ix_solicitud_numero_documento ON TBL_SolicitudInscripcion (Numero_Documento);
CREATE INDEX IF NOT EXISTS ix_solicitud_fecha_radicacion ON TBL_SolicitudInscripcion (Fecha_Radicacion DESC);


-- 3. TBL_DocumentoInscripcion
-- =============================================================================
CREATE TABLE IF NOT EXISTS TBL_DocumentoInscripcion (
    ID              INT GENERATED BY DEFAULT AS IDENTITY,
    Solicitud_ID    INT          NOT NULL,
    Nombre_Archivo  VARCHAR(255) NOT NULL,
    Ruta_Archivo    VARCHAR(500) NOT NULL,
    Tipo_Documento  VARCHAR(50)  NULL,
    Fecha_Subida    TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_documentoinscripcion           PRIMARY KEY (ID),
    CONSTRAINT uq_documentoinscripcion_ruta      UNIQUE (Ruta_Archivo),
    CONSTRAINT fk_documentoinscripcion_solicitud FOREIGN KEY (Solicitud_ID)
        REFERENCES TBL_SolicitudInscripcion (ID) ON UPDATE CASCADE ON DELETE CASCADE
);
COMMENT ON TABLE  TBL_DocumentoInscripcion                IS 'Documentos soporte (PDF o imágenes) adjuntos a cada solicitud.';
COMMENT ON COLUMN TBL_DocumentoInscripcion.Nombre_Archivo IS 'Nombre original del archivo tal como lo subió el aspirante.';
COMMENT ON COLUMN TBL_DocumentoInscripcion.Ruta_Archivo   IS 'Ruta relativa a la carpeta backend (uploads/documentos/...).';
COMMENT ON COLUMN TBL_DocumentoInscripcion.Tipo_Documento IS 'Tipo MIME del archivo (application/pdf, image/jpeg...).';

CREATE INDEX IF NOT EXISTS ix_documentoinscripcion_solicitud ON TBL_DocumentoInscripcion (Solicitud_ID);


-- 4. TBL_ConsecutivoRadicado
-- =============================================================================
-- Un registro por año. La API lo incrementa con INSERT ... ON CONFLICT DO UPDATE
-- dentro de la misma transacción que guarda la solicitud: la fila queda bloqueada
-- hasta el COMMIT, así dos radicaciones simultáneas nunca obtienen el mismo número
-- y un fallo (ROLLBACK) no deja huecos en la numeración.
CREATE TABLE IF NOT EXISTS TBL_ConsecutivoRadicado (
    Anio    INT NOT NULL,
    Ultimo  INT NOT NULL DEFAULT 0,
    CONSTRAINT pk_consecutivoradicado        PRIMARY KEY (Anio),
    CONSTRAINT ck_consecutivoradicado_ultimo CHECK (Ultimo >= 0)
);
COMMENT ON TABLE TBL_ConsecutivoRadicado IS 'Último consecutivo de radicado emitido en cada año.';

-- Si ya existían solicitudes con radicado, el contador continúa desde el mayor emitido.
INSERT INTO TBL_ConsecutivoRadicado (Anio, Ultimo)
SELECT split_part(Numero_Radicado, '-', 2)::INT, MAX(split_part(Numero_Radicado, '-', 3)::INT)
FROM TBL_SolicitudInscripcion
WHERE Numero_Radicado ~ '^RAD-[0-9]{4}-[0-9]+$'
GROUP BY 1
ON CONFLICT (Anio) DO UPDATE SET Ultimo = GREATEST(TBL_ConsecutivoRadicado.Ultimo, EXCLUDED.Ultimo);


-- 5. Programas ofrecidos (datos semilla)
-- =============================================================================
INSERT INTO TBL_Programas (Programa) VALUES
    ('Música'),
    ('Danza'),
    ('Teatro'),
    ('Artes plásticas'),
    ('Literatura y escritura creativa'),
    ('Artesanías y oficios')
ON CONFLICT (Programa) DO NOTHING;

COMMIT;
