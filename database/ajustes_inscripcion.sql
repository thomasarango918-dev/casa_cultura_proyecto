-- =============================================================================
--  Casa de la Cultura de San Pedro de los Milagros
--  FASE 2 - AJUSTES: fecha de nacimiento, edad, acudiente y documentos requeridos
--  Script de actualización PostgreSQL (14+).
-- -----------------------------------------------------------------------------
--  Orden de ejecución:
--      1. database/casacultura.sql          (esquema inicial)
--      2. database/fase2_solicitudes.sql    (Fase 2)
--      3. database/fase2_ajustes_inscripcion.sql   <- ESTE ARCHIVO
--
--  Ejecución (pgAdmin > Query Tool sobre la base casacultura, o por consola):
--      psql -U casacultura -d casacultura -f database/fase2_ajustes_inscripcion.sql
--
--  Qué hace:
--    1. Crea el catálogo TBL_Parentesco (lista desplegable del acudiente).
--    2. Crea el catálogo TBL_RequisitoDocumento (documentos que debe subir el aspirante):
--         DOCUMENTO_IDENTIDAD   Documento de identidad escaneado
--         CERTIFICADO_EPS       Certificado de EPS
--         FORMATO_INSCRIPCION   Formato de inscripción firmado (Oficina de Cultura)
--    3. Agrega a TBL_SolicitudInscripcion: fecha de nacimiento, edad y datos del acudiente.
--    4. Agrega a TBL_DocumentoInscripcion la columna Requisito (qué documento es cada archivo).
--
--  Es idempotente: ejecutarlo de nuevo no cambia nada ni borra datos.
--  No modifica TBL_Usuarios, TBL_Roles ni TBL_TipoDocumento.
--  Las columnas nuevas admiten NULL solo para no romper solicitudes radicadas antes
--  de este ajuste; la API las exige en todas las solicitudes nuevas.
-- =============================================================================

BEGIN;

SET client_encoding = 'UTF8';


-- 1. TBL_Parentesco
-- =============================================================================
CREATE TABLE IF NOT EXISTS TBL_Parentesco (
    ID          INT GENERATED BY DEFAULT AS IDENTITY,
    Parentesco  VARCHAR(30) NOT NULL,
    Orden       INT         NOT NULL DEFAULT 0,
    CONSTRAINT pk_parentesco            PRIMARY KEY (ID),
    CONSTRAINT uq_parentesco_parentesco UNIQUE (Parentesco)
);
COMMENT ON TABLE TBL_Parentesco IS 'Catálogo de parentescos del acudiente de un aspirante menor de edad.';

INSERT INTO TBL_Parentesco (Parentesco, Orden) VALUES
    ('Madre', 1),
    ('Padre', 2),
    ('Abuelo(a)', 3),
    ('Hermano(a)', 4),
    ('Tío(a)', 5),
    ('Tutor(a) legal', 6),
    ('Otro', 7)
ON CONFLICT (Parentesco) DO NOTHING;


-- 2. TBL_RequisitoDocumento
-- =============================================================================
CREATE TABLE IF NOT EXISTS TBL_RequisitoDocumento (
    Codigo       VARCHAR(40)  NOT NULL,
    Nombre       VARCHAR(100) NOT NULL,
    Descripcion  VARCHAR(255) NULL,
    Orden        INT          NOT NULL DEFAULT 0,
    Obligatorio  BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_requisitodocumento PRIMARY KEY (Codigo),
    CONSTRAINT ck_requisitodocumento_codigo CHECK (Codigo = UPPER(Codigo))
);
COMMENT ON TABLE  TBL_RequisitoDocumento             IS 'Documentos que el aspirante debe adjuntar al radicar su solicitud.';
COMMENT ON COLUMN TBL_RequisitoDocumento.Codigo      IS 'Identificador que envía el formulario junto a cada archivo.';
COMMENT ON COLUMN TBL_RequisitoDocumento.Obligatorio IS 'TRUE = la solicitud no se radica sin este documento.';

INSERT INTO TBL_RequisitoDocumento (Codigo, Nombre, Descripcion, Orden, Obligatorio) VALUES
    ('DOCUMENTO_IDENTIDAD', 'Documento de identidad escaneado',
     'Copia legible por ambas caras del documento de identidad del aspirante.', 1, TRUE),
    ('CERTIFICADO_EPS', 'Certificado de EPS',
     'Certificado de afiliación a la EPS con fecha reciente.', 2, TRUE),
    ('FORMATO_INSCRIPCION', 'Formato de inscripción firmado',
     'Formato entregado por la Oficina de Cultura, diligenciado y firmado.', 3, TRUE)
ON CONFLICT (Codigo) DO NOTHING;


-- 3. TBL_SolicitudInscripcion: fecha de nacimiento, edad y acudiente
-- =============================================================================
ALTER TABLE TBL_SolicitudInscripcion ADD COLUMN IF NOT EXISTS Fecha_Nacimiento      DATE         NULL;
ALTER TABLE TBL_SolicitudInscripcion ADD COLUMN IF NOT EXISTS Edad                  SMALLINT     NULL;
ALTER TABLE TBL_SolicitudInscripcion ADD COLUMN IF NOT EXISTS Acudiente_Nombre      VARCHAR(150) NULL;
ALTER TABLE TBL_SolicitudInscripcion ADD COLUMN IF NOT EXISTS Acudiente_Documento   VARCHAR(20)  NULL;
ALTER TABLE TBL_SolicitudInscripcion ADD COLUMN IF NOT EXISTS Acudiente_Telefono    VARCHAR(20)  NULL;
ALTER TABLE TBL_SolicitudInscripcion ADD COLUMN IF NOT EXISTS Acudiente_Parentesco  VARCHAR(30)  NULL;

COMMENT ON COLUMN TBL_SolicitudInscripcion.Fecha_Nacimiento     IS 'Fecha de nacimiento del aspirante.';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Edad                 IS 'Edad en años cumplidos al momento de radicar.';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Acudiente_Nombre     IS 'Nombre completo del acudiente (obligatorio si Edad < 18).';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Acudiente_Documento  IS 'Cédula del acudiente.';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Acudiente_Telefono   IS 'Número de contacto del acudiente.';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Acudiente_Parentesco IS 'Parentesco con el aspirante (TBL_Parentesco).';

-- Las restricciones se agregan solo si aún no existen (ADD CONSTRAINT no admite IF NOT EXISTS).
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_solicitud_edad') THEN
        ALTER TABLE TBL_SolicitudInscripcion
            ADD CONSTRAINT ck_solicitud_edad CHECK (Edad IS NULL OR Edad BETWEEN 0 AND 120);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_solicitud_fecha_nacimiento') THEN
        ALTER TABLE TBL_SolicitudInscripcion
            ADD CONSTRAINT ck_solicitud_fecha_nacimiento
            CHECK (Fecha_Nacimiento IS NULL OR Fecha_Nacimiento <= Fecha_Radicacion::DATE);
    END IF;

    -- Un aspirante menor de edad siempre tiene acudiente completo.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_solicitud_acudiente_menor') THEN
        ALTER TABLE TBL_SolicitudInscripcion
            ADD CONSTRAINT ck_solicitud_acudiente_menor CHECK (
                Edad IS NULL OR Edad >= 18 OR (
                    Acudiente_Nombre IS NOT NULL AND Acudiente_Documento IS NOT NULL
                    AND Acudiente_Telefono IS NOT NULL AND Acudiente_Parentesco IS NOT NULL
                )
            );
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_solicitud_acudiente_parentesco') THEN
        ALTER TABLE TBL_SolicitudInscripcion
            ADD CONSTRAINT fk_solicitud_acudiente_parentesco FOREIGN KEY (Acudiente_Parentesco)
            REFERENCES TBL_Parentesco (Parentesco) ON UPDATE CASCADE ON DELETE RESTRICT;
    END IF;
END
$$;


-- 4. TBL_DocumentoInscripcion: requisito al que corresponde cada archivo
-- =============================================================================
ALTER TABLE TBL_DocumentoInscripcion ADD COLUMN IF NOT EXISTS Requisito VARCHAR(40) NULL;
COMMENT ON COLUMN TBL_DocumentoInscripcion.Requisito IS 'Documento requerido al que corresponde el archivo (TBL_RequisitoDocumento). NULL en archivos anteriores a este ajuste.';

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_documentoinscripcion_requisito') THEN
        ALTER TABLE TBL_DocumentoInscripcion
            ADD CONSTRAINT fk_documentoinscripcion_requisito FOREIGN KEY (Requisito)
            REFERENCES TBL_RequisitoDocumento (Codigo) ON UPDATE CASCADE ON DELETE RESTRICT;
    END IF;
END
$$;

-- Un solo archivo por requisito en cada solicitud.
CREATE UNIQUE INDEX IF NOT EXISTS uq_documentoinscripcion_solicitud_requisito
    ON TBL_DocumentoInscripcion (Solicitud_ID, Requisito)
    WHERE Requisito IS NOT NULL;

COMMIT;
