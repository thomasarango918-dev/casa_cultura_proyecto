DECLARE
    r RECORD;
BEGIN
    FOR r IN
        SELECT * FROM (VALUES
            ('tbl_programas', 'fk_programas_categoria',
             'FOREIGN KEY (categoria_id) REFERENCES tbl_categorias (id) ON UPDATE CASCADE ON DELETE RESTRICT'),
            ('tbl_solicitudinscripcion', 'ck_solicitud_edad',
             'CHECK (edad IS NULL OR edad BETWEEN 0 AND 120)'),
            ('tbl_solicitudinscripcion', 'ck_solicitud_fecha_nacimiento',
             'CHECK (fecha_nacimiento IS NULL OR fecha_nacimiento <= fecha_radicacion::DATE)'),
            ('tbl_solicitudinscripcion', 'ck_solicitud_acudiente_menor',
             'CHECK (edad IS NULL OR edad >= 18 OR (acudiente_nombre IS NOT NULL AND acudiente_documento IS NOT NULL AND acudiente_telefono IS NOT NULL AND acudiente_parentesco IS NOT NULL))'),
            ('tbl_solicitudinscripcion', 'fk_solicitud_acudiente_parentesco',
             'FOREIGN KEY (acudiente_parentesco) REFERENCES tbl_parentesco (parentesco) ON UPDATE CASCADE ON DELETE RESTRICT'),
            ('tbl_documentoinscripcion', 'fk_documentoinscripcion_requisito',
             'FOREIGN KEY (requisito) REFERENCES tbl_requisitodocumento (codigo) ON UPDATE CASCADE ON DELETE RESTRICT')
        ) AS v(tabla, nombre, definicion)
    LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = r.nombre) THEN
            EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I %s', r.tabla, r.nombre, r.definicion);
            RAISE NOTICE 'Restricción % agregada a %.', r.nombre, r.tabla;
        END IF;
    END LOOP;
END
$$;


