-- =============================================================================
--  Casa de la Cultura de San Pedro de los Milagros
--  casacultura-V2.sql  -  ESQUEMA COMPLETO CONSOLIDADO (Fases 1 a 8)
-- -----------------------------------------------------------------------------
--  Reemplaza, en un solo archivo, a:
--      casacultura.sql, ajustes_solicitudes.sql, ajustes_inscripcion.sql,
--      fase3_administracion.sql, fase3_configuracion_sistema.sql,
--      fase4_notificaciones.sql, fase4_categorias_programas.sql,
--      fase5_grupos.sql y fase6_asistencias.sql.
--  (Las Fases 7 y 8 no tienen cambios de base de datos.)
--
--  Uso:
--      1. En pgAdmin cree la base de datos  casacultura  (vacía).
--      2. Abra el Query Tool sobre esa base, cargue este archivo y ejecútelo (F5).
--      o por consola:  psql -U postgres -d casacultura -f database/casacultura-V2.sql
--
--  Es IDEMPOTENTE: se puede ejecutar varias veces sin duplicar nada ni borrar datos.
--  Requiere PostgreSQL 13 o superior.
--
--  Convenciones:
--    * Identificadores sin comillas: PostgreSQL los guarda en minúsculas
--      (TBL_Usuarios -> tbl_usuarios). Los modelos SQLAlchemy usan esos nombres.
--    * Claves primarias INT GENERATED BY DEFAULT AS IDENTITY.
--    * Las tablas antiguas de casacultura.sql que el código ya no usa
--      (tbl_estadosolicitud, tbl_archivossolicitud, tbl_inscripciongrupo,
--      tbl_sesionesclase, tbl_asistencias) NO se crean aquí.
-- =============================================================================

BEGIN;

SET client_encoding = 'UTF8';


-- =============================================================================
-- 0. COMPATIBILIDAD CON UNA BASE CREADA CON EL casacultura.sql ORIGINAL
-- -----------------------------------------------------------------------------
--  Si existe la estructura vieja de solicitudes (sin numero_radicado) o de grupos
--  (sin nombre) y está VACÍA, se retira para crear la definitiva. Si tiene datos,
--  el script se detiene sin cambiar nada. En una base nueva este bloque no hace nada.
-- =============================================================================
DO $$
DECLARE
    v_filas BIGINT := 0;
    v_total BIGINT := 0;
    v_tabla TEXT;
BEGIN
    -- Solicitudes (estructura anterior a la Fase 2).
    IF to_regclass('tbl_solicitudinscripcion') IS NOT NULL
       AND NOT EXISTS (
           SELECT 1 FROM information_schema.columns
           WHERE table_schema = current_schema()
             AND table_name = 'tbl_solicitudinscripcion'
             AND column_name = 'numero_radicado'
       ) THEN
        FOREACH v_tabla IN ARRAY ARRAY['tbl_documentoinscripcion', 'tbl_archivossolicitud', 'tbl_solicitudinscripcion'] LOOP
            IF to_regclass(v_tabla) IS NOT NULL THEN
                EXECUTE format('SELECT count(*) FROM %I', v_tabla) INTO v_filas;
                v_total := v_total + v_filas;
            END IF;
        END LOOP;
        IF v_total > 0 THEN
            RAISE EXCEPTION 'Las tablas de solicitudes del esquema anterior tienen % registro(s). Respáldelos y vacíelas antes de ejecutar este script.', v_total;
        END IF;
        DROP TABLE IF EXISTS tbl_documentoinscripcion;
        DROP TABLE IF EXISTS tbl_archivossolicitud;
        DROP TABLE tbl_solicitudinscripcion CASCADE;
        RAISE NOTICE 'Estructura anterior de solicitudes retirada (estaba vacía).';
    END IF;

    -- Grupos (estructura de casacultura.sql: sin nombre y con profesor_id NOT NULL).
    IF to_regclass('tbl_grupos') IS NOT NULL
       AND NOT EXISTS (
           SELECT 1 FROM information_schema.columns
           WHERE table_schema = current_schema()
             AND table_name = 'tbl_grupos'
             AND column_name = 'nombre'
       ) THEN
        EXECUTE 'SELECT count(*) FROM tbl_grupos' INTO v_filas;
        IF v_filas > 0 THEN
            RAISE EXCEPTION 'tbl_grupos del esquema anterior tiene % registro(s). Respáldelos y vacíela antes de ejecutar este script.', v_filas;
        END IF;
        DROP TABLE tbl_grupos CASCADE;
        RAISE NOTICE 'Estructura anterior de grupos retirada (estaba vacía).';
    END IF;
END
$$;


