-- =============================================================================
--  Casa de la Cultura de San Pedro de los Milagros
--  Sistema de gestión académica y radicación pública
--  Script DDL PostgreSQL (14+)
-- -----------------------------------------------------------------------------
--  Convenciones:
--    * Los identificadores se escriben sin comillas, por lo que PostgreSQL los
--      almacena en minúsculas (TBL_Usuarios -> tbl_usuarios, Nom_Role -> nom_role).
--      Los modelos SQLAlchemy usan esos nombres en minúsculas.
--    * Las claves primarias enteras son columnas IDENTITY (BY DEFAULT), lo que
--      permite fijar los ID de los catálogos en los datos semilla.
--    * TBL_Usuarios incluye la columna Password_Hash (bcrypt), necesaria para
--      la autenticación de la API.
-- =============================================================================

BEGIN;

SET client_encoding = 'UTF8';

-- pgcrypto: crypt()/gen_salt() para el hash bcrypt del administrador inicial.
-- gen_random_uuid() es nativo desde PostgreSQL 13.
CREATE EXTENSION IF NOT EXISTS pgcrypto;


-- Limpieza (orden inverso de dependencias)
-- -----------------------------------------------------------------------------
DROP TABLE IF EXISTS TBL_Asistencias          CASCADE;
DROP TABLE IF EXISTS TBL_SesionesClase        CASCADE;
DROP TABLE IF EXISTS TBL_InscripcionGrupo     CASCADE;
DROP TABLE IF EXISTS TBL_Grupos               CASCADE;
DROP TABLE IF EXISTS TBL_ArchivosSolicitud    CASCADE;
DROP TABLE IF EXISTS TBL_SolicitudInscripcion CASCADE;
DROP TABLE IF EXISTS TBL_Programas            CASCADE;
DROP TABLE IF EXISTS TBL_EstadoSolicitud      CASCADE;
DROP TABLE IF EXISTS TBL_Usuarios             CASCADE;
DROP TABLE IF EXISTS TBL_TipoDocumento        CASCADE;
DROP TABLE IF EXISTS TBL_Roles                CASCADE;


-- 1. TBL_Roles
-- =============================================================================

CREATE TABLE TBL_Roles (
    ID        INT GENERATED BY DEFAULT AS IDENTITY,
    Nom_Role  VARCHAR(30) NOT NULL,
    CONSTRAINT pk_roles          PRIMARY KEY (ID),
    CONSTRAINT uq_roles_nom_role UNIQUE (Nom_Role)
);
COMMENT ON TABLE TBL_Roles IS 'Catálogo de roles de acceso al sistema.';


-- 2. TBL_TipoDocumento
-- =============================================================================

CREATE TABLE TBL_TipoDocumento (
    ID        INT GENERATED BY DEFAULT AS IDENTITY,
    Tipo_Doc  VARCHAR(20) NOT NULL,
    CONSTRAINT pk_tipodocumento          PRIMARY KEY (ID),
    CONSTRAINT uq_tipodocumento_tipo_doc UNIQUE (Tipo_Doc)
);
COMMENT ON TABLE TBL_TipoDocumento IS 'Catálogo de tipos de documento de identidad (códigos colombianos).';


-- 3. TBL_Usuarios
-- =============================================================================

CREATE TABLE TBL_Usuarios (
    ID              INT GENERATED BY DEFAULT AS IDENTITY,
    Tipo_Documento  INT          NOT NULL,
    Num_Documento   VARCHAR(20)  NOT NULL,
    Nombre_Com      VARCHAR(100) NOT NULL,
    Email           VARCHAR(150) NOT NULL,
    Password_Hash   VARCHAR(255) NOT NULL,
    Tipo_Role       INT          NOT NULL,
    State           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_usuarios                PRIMARY KEY (ID),
    CONSTRAINT uq_usuarios_email          UNIQUE (Email),
    CONSTRAINT uq_usuarios_num_documento  UNIQUE (Num_Documento),
    CONSTRAINT ck_usuarios_email_min      CHECK (Email = LOWER(Email)),
    CONSTRAINT fk_usuarios_tipo_documento FOREIGN KEY (Tipo_Documento)
        REFERENCES TBL_TipoDocumento (ID) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_usuarios_rol            FOREIGN KEY (Tipo_Role)
        REFERENCES TBL_Roles (ID)         ON UPDATE CASCADE ON DELETE RESTRICT
);
COMMENT ON TABLE  TBL_Usuarios               IS 'Usuarios con acceso al sistema (administración, coordinación, docentes y estudiantes).';
COMMENT ON COLUMN TBL_Usuarios.Num_Documento IS 'Único: se usa como identificador alternativo de inicio de sesión.';
COMMENT ON COLUMN TBL_Usuarios.Password_Hash IS 'Hash bcrypt de la contraseña. Nunca se almacena la contraseña en texto plano.';
COMMENT ON COLUMN TBL_Usuarios.State         IS 'TRUE = cuenta activa; FALSE = cuenta inhabilitada.';

CREATE INDEX ix_usuarios_tipo_role ON TBL_Usuarios (Tipo_Role);


-- 4. TBL_EstadoSolicitud
-- =============================================================================

CREATE TABLE TBL_EstadoSolicitud (
    ID      INT GENERATED BY DEFAULT AS IDENTITY,
    Estado  VARCHAR(20) NOT NULL,
    CONSTRAINT pk_estadosolicitud        PRIMARY KEY (ID),
    CONSTRAINT uq_estadosolicitud_estado UNIQUE (Estado)
);
COMMENT ON TABLE TBL_EstadoSolicitud IS 'Catálogo de estados del flujo de radicación.';


-- 5. TBL_Programas
-- =============================================================================

CREATE TABLE TBL_Programas (
    ID        INT GENERATED BY DEFAULT AS IDENTITY,
    Programa  VARCHAR(100) NOT NULL,
    CONSTRAINT pk_programas          PRIMARY KEY (ID),
    CONSTRAINT uq_programas_programa UNIQUE (Programa)
);
COMMENT ON TABLE TBL_Programas IS 'Programas formativos ofrecidos por la Casa de la Cultura.';


-- 6. TBL_SolicitudInscripcion
-- =============================================================================

CREATE TABLE TBL_SolicitudInscripcion (
    ID              INT GENERATED BY DEFAULT AS IDENTITY,
    Num_Rad         VARCHAR(50)  NOT NULL,
    Tipo_Documento  INT          NOT NULL,
    Num_Documento   VARCHAR(20)  NOT NULL,
    Nombre_Com      VARCHAR(100) NOT NULL,
    Email           VARCHAR(150) NOT NULL,
    Programa_ID     INT          NOT NULL,
    Estado_ID       INT          NOT NULL DEFAULT 1,
    Revisado_User   INT          NULL,
    Usuario_ID      INT          NULL,
    Creado_en       TIMESTAMP    NOT NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_solicitud                PRIMARY KEY (ID),
    CONSTRAINT uq_solicitud_num_rad        UNIQUE (Num_Rad),
    CONSTRAINT fk_solicitud_tipo_documento FOREIGN KEY (Tipo_Documento)
        REFERENCES TBL_TipoDocumento (ID)   ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_programa       FOREIGN KEY (Programa_ID)
        REFERENCES TBL_Programas (ID)       ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_estado         FOREIGN KEY (Estado_ID)
        REFERENCES TBL_EstadoSolicitud (ID) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_solicitud_revisor        FOREIGN KEY (Revisado_User)
        REFERENCES TBL_Usuarios (ID)        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_solicitud_usuario        FOREIGN KEY (Usuario_ID)
        REFERENCES TBL_Usuarios (ID)        ON UPDATE CASCADE ON DELETE SET NULL
);
COMMENT ON TABLE  TBL_SolicitudInscripcion               IS 'Solicitudes de inscripción radicadas desde el formulario público.';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Num_Rad       IS 'Número de radicado entregado al ciudadano.';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Revisado_User IS 'Funcionario que revisó la solicitud (NULL mientras no se revise).';
COMMENT ON COLUMN TBL_SolicitudInscripcion.Usuario_ID    IS 'Cuenta de estudiante creada al aprobar la solicitud (NULL si aún no existe).';

CREATE INDEX ix_solicitud_estado        ON TBL_SolicitudInscripcion (Estado_ID);
CREATE INDEX ix_solicitud_programa      ON TBL_SolicitudInscripcion (Programa_ID);
CREATE INDEX ix_solicitud_num_documento ON TBL_SolicitudInscripcion (Num_Documento);
CREATE INDEX ix_solicitud_creado_en     ON TBL_SolicitudInscripcion (Creado_en DESC);


-- 7. TBL_ArchivosSolicitud
-- =============================================================================

CREATE TABLE TBL_ArchivosSolicitud (
    ID            INT GENERATED BY DEFAULT AS IDENTITY,
    Solicitud_ID  INT          NOT NULL,
    Tipo_Req      VARCHAR(50)  NOT NULL,
    URL_archivo   VARCHAR(255) NOT NULL,
    Es_valido     BOOLEAN      NULL,
    CONSTRAINT pk_archivos           PRIMARY KEY (ID),
    CONSTRAINT fk_archivos_solicitud FOREIGN KEY (Solicitud_ID)
        REFERENCES TBL_SolicitudInscripcion (ID) ON UPDATE CASCADE ON DELETE CASCADE
);
COMMENT ON TABLE  TBL_ArchivosSolicitud           IS 'Documentos soporte adjuntos a cada solicitud de inscripción.';
COMMENT ON COLUMN TBL_ArchivosSolicitud.Es_valido IS 'NULL = pendiente de revisión; TRUE = válido; FALSE = rechazado.';

CREATE INDEX ix_archivos_solicitud ON TBL_ArchivosSolicitud (Solicitud_ID);


-- 8. TBL_Grupos
-- =============================================================================

CREATE TABLE TBL_Grupos (
    ID           INT GENERATED BY DEFAULT AS IDENTITY,
    Programa_ID  INT NOT NULL,
    Profesor_ID  INT NOT NULL,
    CONSTRAINT pk_grupos          PRIMARY KEY (ID),
    CONSTRAINT fk_grupos_programa FOREIGN KEY (Programa_ID)
        REFERENCES TBL_Programas (ID) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_grupos_profesor FOREIGN KEY (Profesor_ID)
        REFERENCES TBL_Usuarios (ID)  ON UPDATE CASCADE ON DELETE RESTRICT
);
COMMENT ON TABLE TBL_Grupos IS 'Grupos de formación: un programa dictado por un docente.';

CREATE INDEX ix_grupos_programa ON TBL_Grupos (Programa_ID);
CREATE INDEX ix_grupos_profesor ON TBL_Grupos (Profesor_ID);


-- 9. TBL_InscripcionGrupo
-- =============================================================================

CREATE TABLE TBL_InscripcionGrupo (
    ID             INT GENERATED BY DEFAULT AS IDENTITY,
    Grupo_ID       INT NOT NULL,
    Estudiante_ID  INT NOT NULL,
    CONSTRAINT pk_inscripcion                  PRIMARY KEY (ID),
    CONSTRAINT uq_inscripcion_grupo_estudiante UNIQUE (Grupo_ID, Estudiante_ID),
    CONSTRAINT fk_inscripcion_grupo            FOREIGN KEY (Grupo_ID)
        REFERENCES TBL_Grupos (ID)   ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_inscripcion_estudiante       FOREIGN KEY (Estudiante_ID)
        REFERENCES TBL_Usuarios (ID) ON UPDATE CASCADE ON DELETE RESTRICT
);
COMMENT ON TABLE TBL_InscripcionGrupo IS 'Matrícula de estudiantes en grupos.';

CREATE INDEX ix_inscripcion_estudiante ON TBL_InscripcionGrupo (Estudiante_ID);


-- 10. TBL_SesionesClase
-- =============================================================================

CREATE TABLE TBL_SesionesClase (
    ID           INT GENERATED BY DEFAULT AS IDENTITY,
    Grupo_ID     INT  NOT NULL,
    Fecha_Clase  DATE NOT NULL,
    CONSTRAINT pk_sesiones             PRIMARY KEY (ID),
    CONSTRAINT uq_sesiones_grupo_fecha UNIQUE (Grupo_ID, Fecha_Clase),
    CONSTRAINT fk_sesiones_grupo       FOREIGN KEY (Grupo_ID)
        REFERENCES TBL_Grupos (ID) ON UPDATE CASCADE ON DELETE CASCADE
);
COMMENT ON TABLE TBL_SesionesClase IS 'Sesiones (fechas de clase) programadas para cada grupo.';


-- 11. TBL_Asistencias
-- =============================================================================

CREATE TABLE TBL_Asistencias (
    ID                    UUID        NOT NULL DEFAULT gen_random_uuid(),
    SesionClase_ID        INT         NOT NULL,
    Estudiante_ID         INT         NOT NULL,
    EstadoAsistencia      VARCHAR(20) NOT NULL,
    Fecha_Registro_Local  TIMESTAMP   NOT NULL,
    Fecha_Sincronizacion  TIMESTAMP   NULL DEFAULT LOCALTIMESTAMP,
    CONSTRAINT pk_asistencias                   PRIMARY KEY (ID),
    CONSTRAINT uq_asistencias_sesion_estudiante UNIQUE (SesionClase_ID, Estudiante_ID),
    CONSTRAINT ck_asistencias_estado            CHECK (EstadoAsistencia IN ('Presente', 'Ausente', 'Tarde', 'Excusa')),
    CONSTRAINT fk_asistencias_sesion            FOREIGN KEY (SesionClase_ID)
        REFERENCES TBL_SesionesClase (ID) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_asistencias_estudiante        FOREIGN KEY (Estudiante_ID)
        REFERENCES TBL_Usuarios (ID)      ON UPDATE CASCADE ON DELETE RESTRICT
);
COMMENT ON TABLE  TBL_Asistencias                      IS 'Registro de asistencia por sesión; admite captura sin conexión (PWA).';
COMMENT ON COLUMN TBL_Asistencias.ID                   IS 'UUID generable en el dispositivo para sincronización idempotente.';
COMMENT ON COLUMN TBL_Asistencias.Fecha_Registro_Local IS 'Momento en que el docente tomó la asistencia en su dispositivo.';
COMMENT ON COLUMN TBL_Asistencias.Fecha_Sincronizacion IS 'Momento en que el registro llegó al servidor.';

CREATE INDEX ix_asistencias_estudiante ON TBL_Asistencias (Estudiante_ID);


